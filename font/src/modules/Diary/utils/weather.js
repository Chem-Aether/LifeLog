const optionsByCode = new Map(weatherOptions.map(option => [option.code, option]))
const groupedOptions = new Map()
for (const option of weatherOptions) {
  if (!groupedOptions.has(option.category)) groupedOptions.set(option.category, [])
  groupedOptions.get(option.category).push(option)
}

export const weatherGroups = [...groupedOptions].map(([category, options]) => ({ category, options }))
export const weatherOption = code => optionsByCode.get(Number(code)) || null
export const weatherIconUrl = code => `/diary/weather/${weatherOption(code)?.icon ?? 99}@1x.png`
